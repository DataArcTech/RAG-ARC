    "    {\"tool\":\"locate\",\"args\":{\"top_k\":5}}\n"
    "  ]},\"rationale\":\"Find the most relevant file(s).\",\"parallelizable\":false}\n"
    "- Step 2: within-file page-level locate + read.pages (replace file_id with the REAL UUID returned by locate):\n"
    "  {\"tool_name\":\"explore\",\"tool_args\":{\"actions\":[\n"
    "    {\"tool\":\"toc.tree\",\"args\":{\"file_id\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"max_depth\":2}},\n"
    "    {\"tool\":\"locate\",\"args\":{\"file\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"focus_query\":\"REPLACE_WITH_KEYWORDS\",\"top_k\":8}},\n"
    "    {\"tool\":\"read.pages\",\"args\":{\"file_id\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"page_start\":12,\"page_end\":14,\"goal\":\"read full pages as citeable evidence\"}}\n"
    "  ]},\"rationale\":\"Use toc.tree + page-level locate to pick where to read, then read full pages before concluding.\",\"parallelizable\":false}\n"
    "- Scoped retrieval + full-page read for table/benefit questions:\n"
    "  {\"tool_name\":\"explore\",\"tool_args\":{\"actions\":[\n"
    "    {\"tool\":\"locate\",\"args\":{\"file\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"focus_query\":\"REPLACE_WITH_KEYWORDS\",\"top_k\":8}},\n"
    "    {\"tool\":\"read.pages\",\"args\":{\"file_id\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"page_start\":12,\"page_end\":14}}\n"
    "  ]},\"rationale\":\"Page-level locate to find relevant pages, then read full pages.\",\"parallelizable\":false}\n"
