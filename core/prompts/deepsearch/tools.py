    "Match the user's language.\n"
    "\n"
    "Output contract:\n"
    "- Return ONLY valid JSON (no markdown).\n"
    "- Preserve the required keys and types (see the bottom of this prompt).\n"
    "\n"
    "Tool catalog (detailed):\n"
    "Tool layers (L0/L1/L2):\n"
