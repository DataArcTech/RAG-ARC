    "    {\"tool\":\"tree.open\",\"args\":{\"file_id\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"section_id\":\"REPLACE_WITH_SECTION_ID\"}},\n"
    "    {\"tool\":\"read.pages\",\"args\":{\"file_id\":\"REPLACE_WITH_REAL_FILE_ID_UUID\",\"page_start\":5,\"page_end\":6}}\n"
